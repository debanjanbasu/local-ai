# Kev hard-v1 (`--dataset hard-v1`)
#
# Kev's deterministic generator (scripts/build_hard_v1.py at HARD_REVISION)
# writes manifest.json (pinned below), development.jsonl and test.jsonl (in
# git) and train.jsonl (gitignored; regenerated byte-identically by the
# generator, which needs the pinned Qwen3.5-4B-Base tokenizer for its length
# and context admission). Only train and development are ever opened: test
# (template 5) stays locked, unread and unscored until the training recipe is
# frozen. Splits follow the surface template, so every evaluation split
# measures transfer to an unseen phrasing:
#
#     Kev train, templates 0-2  -> train
#     Kev train, template 3     -> calibration
#     Kev development (t4)      -> validation
#     Kev test (t5)             -> not read
#
# Question translation (labels are Kev's programmatic labels, unchanged):
#   noul   -> "Yes"/"No" (Kev keys true/false), seeded per-row order as in
#             devtools; criteria descriptions, if any, as "Yes: <desc>".
#   choice -> 3-6 options in Kev's order (its generator balances the gold
#             position); key "not_enough_information" reads
#             "not enough information"; a description is appended as
#             "<name>: <desc>". Single-letter keys (a-f) are anonymous: the
#             option is its description alone.
#   score  -> the 6 ordered level descriptions; target is the level index.
# `option_descriptions=False` drops descriptions from named choice/noul
# options (anonymous options keep theirs: it is their only content). The
# devtools renderer and its bytes are unchanged.
# ---------------------------------------------------------------------------


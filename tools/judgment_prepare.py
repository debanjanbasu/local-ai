def kev_render(value, indent: int = 0) -> str:
    """Kev's `kev.api.render`: the text the model reads for a JSON state."""
    pad = "  " * indent
    if value is None:
        return ""
    if isinstance(value, (str, int, float, bool)):
        return str(value)
    if isinstance(value, list):
        return "\n".join(
            f"{pad}- {kev_render(item, indent + 1).lstrip()}" for item in value
        )
    return "\n".join(
        f"{pad}{key}:\n{kev_render(item, indent + 1)}"
        if isinstance(item, (dict, list))
        else f"{pad}{key}: {kev_render(item)}"
        for key, item in value.items()
    )


def load_hard_manifest(kev_dir: Path, expected_sha256: str) -> tuple[dict, str]:
    data = (kev_dir / "manifest.json").read_bytes()
    digest = sha256_hex(data)
    if digest != expected_sha256:
        raise PrepareError(
            f"manifest.json sha256 {digest} does not match pinned {expected_sha256}"
        )
    manifest = json.loads(data, object_pairs_hook=_strict_object)
    expected = {
        "version": HARD_VERSION,
        "partitions": ["train", "development", "test"],
        "families": list(HARD_FAMILIES),
        "templates": {k: list(v) for k, v in HARD_TEMPLATES.items()},
        "trainable_sources": [f"hard_{f}" for f in HARD_FAMILIES],
        "eval_only_sources": [],
        "eval_only": False,
        "tokenizer": HARD_TOKENIZER,
    }
    for key, value in expected.items():
        if manifest.get(key) != value:
            raise PrepareError(f"manifest {key} {manifest.get(key)!r} != {value!r}")
    if "test" not in manifest.get("locked", []):
        raise PrepareError("manifest does not lock the test partition")
    for name in ("train.jsonl", "development.jsonl", "test.jsonl"):
        entry = manifest.get("files", {}).get(name)
        if not isinstance(entry, dict) or not all(
            isinstance(entry.get(k), int) for k in ("bytes", "records", "questions")
        ):
            raise PrepareError(f"manifest has no complete files entry for {name}")
        if not isinstance(entry.get("sha256"), str) or not HEX64.fullmatch(
            entry["sha256"]
        ):
            raise PrepareError(f"manifest {name} lacks a sha256")
    return manifest, digest


def load_hard_partition(kev_dir: Path, partition: str, manifest: dict) -> list[dict]:
    """Load and fully validate train or development; test is refused."""
    if partition not in HARD_SPLITS:
        raise PrepareError(f"hard-v1 partition {partition!r} is never read")
    name = f"{partition}.jsonl"
    entry = manifest["files"][name]
    data = (kev_dir / name).read_bytes()
    digest = sha256_hex(data)
    if digest != entry["sha256"]:
        raise PrepareError(
            f"{name}: sha256 {digest} does not match manifest {entry['sha256']}"
        )
    if len(data) != entry["bytes"]:
        raise PrepareError(f"{name}: {len(data)} bytes, manifest says {entry['bytes']}")
    lines = data.decode("utf-8").split("\n")
    if lines and lines[-1] == "":
        lines.pop()
    records = []
    for number, line in enumerate(lines, 1):
        where = f"{name}:{number}"
        try:
            record = json.loads(line, object_pairs_hook=_strict_object)
        except (json.JSONDecodeError, PrepareError) as error:
            raise PrepareError(f"{where}: invalid JSON record: {error}") from error
        check_hard_record(record, partition, where)
        records.append(record)
    questions = sum(len(r["questions"]) for r in records)
    if (len(records), questions) != (entry["records"], entry["questions"]):
        raise PrepareError(
            f"{name}: {len(records)} records / {questions} questions, manifest says "
            f"{entry['records']} / {entry['questions']}"
        )
    by_family = entry.get("by_family")
    if isinstance(by_family, dict):
        seen = defaultdict(lambda: [0, 0])
        for r in records:
            seen[r["_meta"]["family"]][0] += 1
            seen[r["_meta"]["family"]][1] += len(r["questions"])
        declared = {
            f: [v.get("records"), v.get("questions")] for f, v in by_family.items()
        }
        if dict(seen) != declared:
            raise PrepareError(
                f"{name}: per-family counts {dict(seen)} != manifest {declared}"
            )
    return records


def check_hard_record(record, partition: str, where: str) -> None:
    if not isinstance(record, dict) or set(record) != RECORD_KEYS:
        raise PrepareError(
            f"{where}: record must have exactly the keys {sorted(RECORD_KEYS)}"
        )
    meta = record["_meta"]
    if not isinstance(meta, dict) or not HARD_META_REQUIRED <= set(meta):
        raise PrepareError(f"{where}: _meta must include {sorted(HARD_META_REQUIRED)}")
    family = meta["family"]
    if family not in HARD_FAMILIES:
        raise PrepareError(f"{where}: unsupported family {family!r}")
    if meta["source"] != f"hard_{family}":
        raise PrepareError(f"{where}: source {meta['source']!r} for family {family}")
    if meta["split"] != partition or meta["variant"] != "clean":
        raise PrepareError(f"{where}: _meta split/variant {meta['split']!r}/{meta['variant']!r}")
    prefix = f"hard-v1/{family}/{partition}/"
    if not re.fullmatch(re.escape(prefix) + r"\d{5}", str(meta["id"])):
        raise PrepareError(f"{where}: unexpected id {meta['id']!r}")
    if meta["group_id"] != meta["id"] and not re.fullmatch(
        re.escape(prefix) + r"g\d{5}", str(meta["group_id"])
    ):
        raise PrepareError(f"{where}: unexpected group_id {meta['group_id']!r}")
    match = re.fullmatch(re.escape(family) + r"/t(\d)", str(meta["template"]))
    if not match or int(match.group(1)) not in HARD_TEMPLATES[partition]:
        raise PrepareError(
            f"{where}: template {meta['template']!r} is not a {partition} template"
        )
    if not isinstance(meta["facts"], dict):
        raise PrepareError(f"{where}: _meta.facts must be an object")
    if type(meta["state_tokens"]) is not int or meta["state_tokens"] < 1:
        raise PrepareError(f"{where}: _meta.state_tokens must be a positive integer")
    if not isinstance(meta["text_sha256"], str) or not HEX64.fullmatch(
        meta["text_sha256"]
    ):
        raise PrepareError(f"{where}: _meta.text_sha256 must be a sha256 hex digest")
    state = record["state"]
    if not isinstance(state, (str, dict, list)) or not kev_render(state).strip():
        raise PrepareError(f"{where}: state must be non-empty text or JSON")
    if normalized_text_hash(kev_render(state)) != meta["text_sha256"]:
        raise PrepareError(f"{where}: _meta.text_sha256 does not match the state")
    questions = record["questions"]
    if not isinstance(questions, dict) or not questions:
        raise PrepareError(f"{where}: questions must be a non-empty object")
    for qid, question in questions.items():
        hard_options(question, f"{where}: {qid}", meta["source"], True)


def _option_name(key: str) -> str:
    return key.replace("_", " ")


def hard_options(question, where: str, source: str, descriptions: bool):
    """Validate one question; return [(option text, native key)] in Kev order."""
    qtype = question.get("type") if isinstance(question, dict) else None
    if qtype not in HARD_QUESTION_KEYS:
        raise PrepareError(f"{where}: unsupported question type {qtype!r}")
    required, optional = HARD_QUESTION_KEYS[qtype]
    if not required <= set(question) <= required | optional:
        raise PrepareError(
            f"{where}: {qtype} question keys {sorted(question)} != {sorted(required)}"
        )
    if question["src"] != source:
        raise PrepareError(f"{where}: src {question['src']!r} != {source!r}")
    if not isinstance(question["instructions"], str) or not question["instructions"].strip():
        raise PrepareError(f"{where}: instructions must be non-empty text")
    label, criteria = question["label"], question.get("criteria")
    if qtype == "noul":
        if type(label) is not bool:
            raise PrepareError(f"{where}: noul label must be a boolean")
        criteria = criteria or {}
        if not isinstance(criteria, dict) or not set(criteria) <= {"true", "false"}:
            raise PrepareError(f"{where}: noul criteria may only describe true/false")
        options = []
        for text, value in NOUL_OPTIONS:
            desc = criteria.get(str(value).lower())
            if desc is not None and not isinstance(desc, str):
                raise PrepareError(f"{where}: noul descriptions must be text")
            options.append((f"{text}: {desc}" if descriptions and desc else text, value))
    elif qtype == "choice":
        low, high = HARD_CHOICE_OPTIONS
        if not isinstance(criteria, dict) or not low <= len(criteria) <= high:
            raise PrepareError(f"{where}: choice needs {low}-{high} options")
        if label not in criteria:
            raise PrepareError(f"{where}: choice label {label!r} is not an option")
        options = []
        for key, desc in criteria.items():
            if not re.fullmatch(r"[a-z0-9]+(_[a-z0-9]+)*", key):
                raise PrepareError(f"{where}: unsupported option key {key!r}")
            if desc is not None and not isinstance(desc, str):
                raise PrepareError(f"{where}: option {key!r} description must be text")
            if ANONYMOUS_KEY.fullmatch(key):
                if not desc:
                    raise PrepareError(f"{where}: anonymous option {key!r} has no text")
                text = desc
            elif descriptions and desc:
                text = f"{_option_name(key)}: {desc}"
            else:
                text = _option_name(key)
            options.append((text, key))
    else:
        if not isinstance(criteria, list) or len(criteria) != HARD_SCORE_LEVELS:
            raise PrepareError(f"{where}: score needs {HARD_SCORE_LEVELS} levels")
        if type(label) is not int or not 0 <= label < len(criteria):
            raise PrepareError(f"{where}: score label must be a level index")
        if not all(isinstance(level, str) and level for level in criteria):
            raise PrepareError(f"{where}: score levels must be non-empty text")
        options = [(level, index) for index, level in enumerate(criteria)]
    texts = [text for text, _ in options]
    if len(set(texts)) != len(texts) or any("\n" in t or not t.strip() for t in texts):
        raise PrepareError(f"{where}: option texts must be distinct single lines")
    return options


def hard_candidates(records_by_partition, seed, excluded, descriptions, include):
    renderer = HARD_RENDERER if descriptions else HARD_RENDERER_NO_DESCRIPTIONS
    seen = {}
    for partition, records in records_by_partition.items():
        for record in records:
            meta = record["_meta"]
            row_sha = sha256_hex(
                json.dumps(record, sort_keys=True, ensure_ascii=False).encode("utf-8")
            )
            for key in (meta["id"], row_sha):
                if key in seen:
                    raise PrepareError(f"record {key} repeats ({seen[key]}, {partition})")
                seen[key] = partition
            family = meta["family"]
            if family in HARD_ROUND1_EXCLUDED and family not in include:
                reason = HARD_ROUND1_EXCLUDED[family]
                excluded[reason][partition][f"{family}/records"] += 1
                excluded[reason][partition][f"{family}/questions"] += len(
                    record["questions"]
                )
                continue
            template = int(meta["template"].rsplit("/t", 1)[1])
            split = HARD_SPLITS[partition][template]
            state_text = kev_render(record["state"])
            for qid, question in record["questions"].items():
                options = hard_options(question, meta["id"], meta["source"], descriptions)
                if question["type"] == "noul":
                    options = permute_options(options, seed, f"{meta['id']}/{qid}")
                text, ends = render(state_text, question["instructions"], options)
                keys = [value for _, value in options]
                yield {
                    "id": f"kev-{HARD_VERSION}/{meta['id'].split('/', 1)[1]}/{qid}",
                    "text": text,
                    "token_end_offsets": ends,
                    "metadata": {
                        "split": split,
                        "dataset": HARD_VERSION,
                        "target": keys.index(question["label"]),
                        "options": [t for t, _ in options],
                        "option_labels": keys,
                        "option_count": len(options),
                        "native_label": question["label"],
                        "task": family,
                        "family": family,
                        "question": qid,
                        "question_type": question["type"],
                        "source": meta["source"],
                        "template": meta["template"],
                        "kev_id": meta["id"],
                        "group_id": meta["group_id"],
                        "kev_partition": partition,
                        "row_sha256": row_sha,
                        "text_sha256": meta["text_sha256"],
                        "renderer": renderer,
                        **{k: meta.get(k) for k in HARD_META_COPY},
                    },
                    "_state": json.dumps(
                        record["state"], sort_keys=True, ensure_ascii=False
                    ),
                    "_state_text": state_text,
                }


def check_hard_splits(rows, min_groups: int, families) -> dict:
    """Overlaps, then per split and family: groups, label diversity per question
    type, and coverage of every train (family, question type) cell."""
    check_overlaps(rows)
    cells = defaultdict(list)
    for row in rows:
        meta = row["metadata"]
        cells[(meta["split"], meta["family"])].append(row)
    train_types = {
        (f, r["metadata"]["question_type"])
        for (s, f), cell in cells.items()
        if s == "train"
        for r in cell
    }
    counts = {}
    for split in ("train", "calibration", "validation"):
        counts[split] = {}
        for family in families:
            cell = cells.get((split, family), [])
            groups = {r["metadata"]["group_id"] for r in cell}
            if len(groups) < min_groups:
                raise PrepareError(
                    f"{split}/{family}: {len(groups)} groups, need {min_groups}"
                )
            by_type = defaultdict(list)
            for r in cell:
                by_type[r["metadata"]["question_type"]].append(r)
            for qtype in sorted({t for f, t in train_types if f == family}):
                if qtype not in by_type:
                    raise PrepareError(f"{split}/{family}: no {qtype} questions")
            types = {}
            for qtype, typed in sorted(by_type.items()):
                labels = Counter(
                    json.dumps(r["metadata"]["native_label"]) for r in typed
                )
                targets = Counter(
                    f"{r['metadata']['target']}/{r['metadata']['option_count']}"
                    for r in typed
                )
                if len(labels) < 2:
                    raise PrepareError(
                        f"{split}/{family}/{qtype}: one class only "
                        f"(labels {dict(labels)}, targets {dict(targets)})"
                    )
                types[qtype] = {
                    "rows": len(typed),
                    "questions": dict(
                        sorted(Counter(r["metadata"]["question"] for r in typed).items())
                    ),
                    "option_counts": dict(
                        sorted(
                            Counter(str(r["metadata"]["option_count"]) for r in typed).items()
                        )
                    ),
                    "targets": dict(sorted(targets.items())),
                }
            counts[split][family] = {
                "rows": len(cell),
                "records": len({r["metadata"]["kev_id"] for r in cell}),
                "groups": len(groups),
                "templates": dict(
                    sorted(Counter(r["metadata"]["template"] for r in cell).items())
                ),
                "question_types": types,
            }
    return counts


def _rows_payload(rows) -> bytes:
    return "".join(
        json.dumps(
            {k: r[k] for k in ("id", "text", "token_end_offsets", "metadata")},
            ensure_ascii=False,
            sort_keys=True,
        )
        + "\n"
        for r in rows
    ).encode("utf-8")


def prepare_hard_v1(
    kev_dir: Path,
    out: Path,
    *,
    seed: str = DEFAULT_SEED,
    pilot_rows: int | None = None,
    min_groups: int = 2,
    manifest_sha256: str = HARD_MANIFEST_SHA256,
    option_descriptions: bool = True,
    include_families: tuple[str, ...] = (),
) -> dict:
    """Validate Kev hard-v1 train/development and write rows.jsonl + report.json."""
    kev_dir, out = Path(kev_dir), Path(out)
    if out.exists() or out.is_symlink():
        raise PrepareError(f"{out} already exists; refusing to overwrite")
    if min_groups < 1 or (pilot_rows is not None and pilot_rows < 1):
        raise PrepareError("min groups and pilot rows must be positive")
    unknown = set(include_families) - set(HARD_ROUND1_EXCLUDED)
    if unknown:
        raise PrepareError(f"only {sorted(HARD_ROUND1_EXCLUDED)} can be included, not {sorted(unknown)}")
    manifest, manifest_digest = load_hard_manifest(kev_dir, manifest_sha256)
    records = {p: load_hard_partition(kev_dir, p, manifest) for p in HARD_SPLITS}
    excluded = defaultdict(lambda: defaultdict(Counter))
    rows = list(
        hard_candidates(records, seed, excluded, option_descriptions, set(include_families))
    )
    if pilot_rows is not None:
        rows = apply_pilot_cap(rows, seed, pilot_rows, excluded)
    present = {r["_meta"]["family"] for part in records.values() for r in part}
    families = [
        f
        for f in HARD_FAMILIES
        if f in present and (f not in HARD_ROUND1_EXCLUDED or f in include_families)
    ]
    counts = check_hard_splits(rows, min_groups, families)
    rows.sort(
        key=lambda r: (
            SPLIT_ORDER.index(r["metadata"]["split"]),
            hash_key(seed, "order", r["id"]),
        )
    )
    payload = _rows_payload(rows)
    files = manifest["files"]
    report = {
        "format": FORMAT,
        "dataset": HARD_VERSION,
        "renderer": HARD_RENDERER if option_descriptions else HARD_RENDERER_NO_DESCRIPTIONS,
        "options": {
            "seed": seed,
            "pilot_rows": pilot_rows,
            "min_groups": min_groups,
            "option_descriptions": option_descriptions,
            "include_families": sorted(include_families),
        },
        "kev": {
            "repository": KEV_REPOSITORY,
            "revision": HARD_REVISION,
            "generator": "scripts/build_hard_v1.py",
            "manifest_url": f"{HARD_BASE_URL}/manifest.json",
            "manifest_sha256": manifest_digest,
            "manifest_pinned": manifest_digest == HARD_MANIFEST_SHA256,
            "version": manifest["version"],
            "seed": manifest.get("seed"),
            "tokenizer": manifest["tokenizer"],
            "code_sha256": manifest.get("code_sha256"),
            "licence": (
                "Apache-2.0 (Kev repository: generator code and its programmatic "
                "output); no third-party source text"
            ),
            "labels": manifest.get("labels"),
            "files": {
                name: {
                    **{k: files[name][k] for k in ("sha256", "bytes", "records", "questions")},
                    "read": name != "test.jsonl",
                }
                for name in ("train.jsonl", "development.jsonl", "test.jsonl")
            },
        },
        "split_map": {
            "train": "Kev train, templates 0-2",
            "calibration": "Kev train, template 3",
            "validation": "Kev development, template 4",
            "test": "Kev test, template 5: locked, not read",
        },
        "translation": {
            "noul": "Yes/No (Kev true/false), seeded per-row order",
            "choice": f"{HARD_CHOICE_OPTIONS[0]}-{HARD_CHOICE_OPTIONS[1]} options, Kev order; "
            "underscores read as spaces; single-letter keys show their description only",
            "score": f"{HARD_SCORE_LEVELS} ordered levels; target is the level index",
        },
        "counts": counts,
        "excluded_rows": {
            reason: {
                part: dict(sorted(c.items())) for part, c in sorted(by_part.items())
            }
            for reason, by_part in sorted(excluded.items())
        },
        "output": {
            "rows": "rows.jsonl",
            "row_count": len(rows),
            "sha256": sha256_hex(payload),
        },
        "caveats": HARD_CAVEATS,
    }
    out.mkdir(parents=True)
    with open(out / "rows.jsonl", "xb") as handle:
        handle.write(payload)
    with open(out / "report.json", "x", encoding="utf-8") as handle:
        handle.write(
            json.dumps(report, indent=2, sort_keys=True, ensure_ascii=False) + "\n"
        )
    return report


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument(
        "--kev-dir",
        type=Path,
        required=True,
        help="directory with manifest.json, train/development/test.jsonl",
    )
    parser.add_argument("--out", type=Path, required=True, help="new output directory")
    parser.add_argument("--seed", default=DEFAULT_SEED)
    parser.add_argument(
        "--dataset",
        choices=(KEV_VERSION, HARD_VERSION),
        default=KEV_VERSION,
        help="Kev suite layout (default devtools-v1)",
    )
    parser.add_argument(
        "--calibration-fraction",
        type=float,
        default=None,
        help="devtools-v1 only (default 0.1); hard-v1 calibrates on template 3",
    )
    parser.add_argument(
        "--pilot-rows",
        type=int,
        default=None,
        help="per split and task, keep whole groups up to N rows",
    )
    parser.add_argument(
        "--min-groups", type=int, default=2, help="minimum groups per split and task"
    )
    parser.add_argument(
        "--manifest-sha256",
        default=None,
        help="override only for test fixtures; defaults to the dataset's pin",
    )
    parser.add_argument(
        "--no-option-descriptions",
        action="store_true",
        help="hard-v1 only: render named options without their descriptions",
    )
    parser.add_argument(
        "--include-long-policy",
        action="store_true",
        help="hard-v1 only: keep long_policy (excluded in round 1)",
    )
    args = parser.parse_args(argv)
    try:
        if args.dataset == HARD_VERSION:
            if args.calibration_fraction is not None:
                raise PrepareError("hard-v1 calibrates on template 3, not a fraction")
            report = prepare_hard_v1(
                args.kev_dir,
                args.out,
                seed=args.seed,
                pilot_rows=args.pilot_rows,
                min_groups=args.min_groups,
                manifest_sha256=args.manifest_sha256 or HARD_MANIFEST_SHA256,
                option_descriptions=not args.no_option_descriptions,
                include_families=("long_policy",) if args.include_long_policy else (),
            )
        else:
            if args.no_option_descriptions or args.include_long_policy:
                raise PrepareError("option descriptions and long_policy are hard-v1 options")
            report = prepare(
                args.kev_dir,
                args.out,
                seed=args.seed,
                calibration_fraction=(
                    0.1 if args.calibration_fraction is None else args.calibration_fraction
                ),
                pilot_rows=args.pilot_rows,
                min_groups=args.min_groups,
                manifest_sha256=args.manifest_sha256 or PINNED_MANIFEST_SHA256,
            )
    except (PrepareError, OSError, UnicodeDecodeError) as error:
        print(f"judgment_prepare: {error}", file=sys.stderr)
        return 2
    print(
        json.dumps({"counts": report["counts"], "output": report["output"]}, indent=2)
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
